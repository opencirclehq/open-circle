it("likes comments and replies, prevents duplicate submissions and preserves counts after a failed unlike", async () => {
  const post = await commandForum(store, admin, command({ action: "create", kind: "discussion", content, publish: true }));
  const commented = await commandForum(store, bob, command({ action: "comment", id: post.id, body: "A helpful explanation" }));
  await commandForum(store, alice, command({ action: "comment", id: post.id, parentId: commented.comments[0].id, body: "A helpful reply" }));
  const user = userEvent.setup();
  render(wrap(<Community />, `/community/${post.id}`));
  const like = await screen.findByRole("button", { name: "Like comment by @Bob" });
  let finish!: () => void;
  const pending = new Promise<void>((resolve) => { finish = resolve; });
  vi.mocked(forumApi.command).mockImplementationOnce(async (input) => { await pending; return commandForum(store, alice, input); });
  await user.click(like);
  expect((like as HTMLButtonElement).disabled).toBe(true);
  await user.click(like);
  expect(forumApi.command).toHaveBeenCalledTimes(1);
  finish();
  const liked = await screen.findByRole("button", { name: "Unlike comment by @Bob" });
  expect(liked.getAttribute("aria-pressed")).toBe("true");
  expect(liked.textContent).toContain("1");
  vi.mocked(forumApi.command).mockRejectedValueOnce(new ApiError(503, "unavailable", "Could not save your like. Try again."));
  await user.click(liked);
  await screen.findByRole("alert");
  expect(screen.getByRole("button", { name: "Unlike comment by @Bob" }).getAttribute("aria-pressed")).toBe("true");
  expect((await readForum(store, alice, post.id)).comments.find((c) => c.id === commented.comments[0].id)?.likeCount).toBe(1);
  await user.click(screen.getByRole("button", { name: "Unlike comment by @Bob" }));
  await screen.findByRole("button", { name: "Like comment by @Bob" });
  await user.click(screen.getByRole("button", { name: "Like comment by @Alice" }));
  await screen.findByRole("button", { name: "Unlike comment by @Alice" });
  expect((await readForum(store, alice, post.id)).likeCount).toBe(0);
  const comments = screen.getByRole("region", { name: "Comments 2" });
  expect(within(comments).getAllByRole("button", { name: "Reply" })).toHaveLength(1);
});
